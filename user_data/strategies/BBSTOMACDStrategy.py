    def populate_entry_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        """
        Based on TA indicators, populates the entry signal for the given dataframe
        :param dataframe: DataFrame
        :param metadata: Additional information, like the currently traded pair
        :return: DataFrame with entry columns populated
        """
        dataframe.loc[
            (
                (dataframe["close"] < dataframe["bb_lowerband"]) &  # Price below lower BB
                (qtpylib.crossed_above(dataframe["macd"], dataframe["macdsignal"])) &  # MACD cross up
                (qtpylib.crossed_above(dataframe["fastk"], dataframe["fastd"])) &  # Stochastic cross up
                (dataframe["fastk"] < 20) &  # Stochastic in oversold
                (dataframe["obv"] > dataframe["obv_ma_12"])  # OBV confirms up move

            ),
            "enter_long",
        ] = 1

        return dataframe

    def populate_exit_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        """
        Based on TA indicators, populates the exit signal for the given dataframe
        :param dataframe: DataFrame
        :param metadata: Additional information, like the currently traded pair
        :return: DataFrame with exit columns populated
        """
        dataframe.loc[
            (
                (dataframe["close"] > dataframe["bb_upperband"]) |  # Price above upper BB
                (qtpylib.crossed_below(dataframe["macd"], dataframe["macdsignal"])) |  # MACD cross down
                (
                    (qtpylib.crossed_below(dataframe["fastk"], dataframe["fastd"])) &
                    (dataframe["fastk"] > 80)  # Stochastic cross down in overbought
                ) |
                (dataframe["obv"] < dataframe["obv_ma_12"])  # OBV weakens
            ),
            "exit_long",
        ] = 1

        return dataframe
